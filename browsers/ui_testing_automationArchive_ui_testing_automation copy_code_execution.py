class TestExecutor:
    """Core test execution engine"""
    
    def __init__(self, config: ExecutionConfig):
        self.config = config
        self.sandbox = SecuritySandbox(config.security_level)
        self.dependency_manager = DependencyManager(config)
        self.results = []
        self.suite = TestSuite(name="Test Execution Suite", test_files=[])
        
        # Ensure output directory exists
        self.config.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Setup temp directory
        if not self.config.temp_dir:
            self.config.temp_dir = Path(tempfile.mkdtemp(prefix="test_exec_"))
    
    async def execute_code(self, code: str, test_name: str = "test") -> TestResult:
        """Execute a single piece of test code"""
        start_time = datetime.now()
        result = TestResult(
            test_name=test_name,
            test_file="<string>",
            status=TestStatus.PENDING,
            duration=0.0,
            start_time=start_time,
            end_time=start_time
        )
        
        try:
            # Validate code security
            is_safe, violations = self.sandbox.validate_code(code)
            if not is_safe:
                result.status = TestStatus.ERROR
                result.error_message = f"Security violations: {', '.join(violations)}"
                return result
            
            # Execute based on mode
            if self.config.execution_mode == ExecutionMode.CONTAINERIZED:
                result = await self._execute_in_container(code, test_name)
            else:
                result = await self._execute_locally(code, test_name)
            
        except Exception as e:
            result.status = TestStatus.ERROR
            result.error_message = str(e)
            result.error_trace = traceback.format_exc()
        finally:
            result.end_time = datetime.now()
            result.duration = (result.end_time - result.start_time).total_seconds()
        
        return result
    
    async def _execute_locally(self, code: str, test_name: str) -> TestResult:
        """Execute code locally with sandboxing"""
        result = TestResult(
            test_name=test_name,
            test_file="<string>",
            status=TestStatus.RUNNING,
            duration=0.0,
            start_time=datetime.now(),
            end_time=datetime.now()
        )
        
        # Monitor resources
        process = psutil.Process()
        initial_memory = process.memory_info().rss / 1024 / 1024  # MB
        
        # Prepare execution environment
        globals_dict = self.sandbox.create_restricted_globals()
        locals_dict = {}
        
        # Capture output
        stdout_capture = io.StringIO()
        stderr_capture = io.StringIO()
        
        with contextlib.redirect_stdout(stdout_capture), \
             contextlib.redirect_stderr(stderr_capture), \
             self.sandbox.sandbox_context():
            
            try:
                # Execute code with timeout
                # Use loop.run_in_executor for Python < 3.9 compatibility
                loop = asyncio.get_event_loop()
                exec_result = await asyncio.wait_for(
                    loop.run_in_executor(None, exec, code, globals_dict, locals_dict),
                    timeout=self.config.timeout_per_test
                )
                
                # Check for test results in locals
                if "test_passed" in locals_dict:
                    result.status = TestStatus.PASSED if locals_dict["test_passed"] else TestStatus.FAILED
                else:
                    # Assume passed if no exceptions
                    result.status = TestStatus.PASSED
                
                result.output = stdout_capture.getvalue()
                
            except asyncio.TimeoutError:
                result.status = TestStatus.TIMEOUT
                result.error_message = f"Test exceeded timeout of {self.config.timeout_per_test}s"
            except AssertionError as e:
                result.status = TestStatus.FAILED
                result.error_message = str(e)
                result.error_trace = traceback.format_exc()
            except Exception as e:
                result.status = TestStatus.ERROR
                result.error_message = str(e)
                result.error_trace = traceback.format_exc()
        
        # Capture resource usage
        final_memory = process.memory_info().rss / 1024 / 1024
        result.memory_usage_mb = final_memory - initial_memory
        result.cpu_usage_percent = process.cpu_percent()
        
        # Add captured output
        result.output = stdout_capture.getvalue()
        if stderr_capture.getvalue():
            result.error_message += f"\nStderr: {stderr_capture.getvalue()}"
        
        return result
    
    async def _execute_in_container(self, code: str, test_name: str) -> TestResult:
        """Execute code in a Docker container for maximum isolation"""
        result = TestResult(
            test_name=test_name,
            test_file="<container>",
            status=TestStatus.RUNNING,
            duration=0.0,
            start_time=datetime.now(),
            end_time=datetime.now()
        )
        
        if not self.config.docker_image:
            self.config.docker_image = "python:3.9-slim"
        
        try:
            # Create temp file with code
            code_file = self.config.temp_dir / f"{test_name}.py"
            code_file.write_text(code)
            
            # Build docker command
            docker_cmd = [
                "docker", "run", "--rm",
                "-v", f"{code_file}:/test.py",
                "--memory", f"{self.config.memory_limit_mb}m",
                "--cpus", f"{self.config.cpu_limit_percent/100}",
                self.config.docker_image,
                "python", "/test.py"
            ]
            
            # Execute in container
            proc = await asyncio.create_subprocess_exec(
                *docker_cmd,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE
            )
            
            stdout, stderr = await asyncio.wait_for(
                proc.communicate(),
                timeout=self.config.timeout_per_test
            )
            
            result.output = stdout.decode()
            
            if proc.returncode == 0:
                result.status = TestStatus.PASSED
            else:
                result.status = TestStatus.FAILED
                result.error_message = stderr.decode()
            
        except asyncio.TimeoutError:
            result.status = TestStatus.TIMEOUT
            result.error_message = f"Container execution exceeded timeout"
        except Exception as e:
            result.status = TestStatus.ERROR
            result.error_message = str(e)
            result.error_trace = traceback.format_exc()
        
        return result
    
    async def execute_file(self, test_file: Path) -> TestResult:
        """Execute a test file"""
        if not test_file.exists():
            return TestResult(
                test_name=test_file.stem,
                test_file=str(test_file),
                status=TestStatus.ERROR,
                duration=0.0,
                start_time=datetime.now(),
                end_time=datetime.now(),
                error_message=f"Test file not found: {test_file}"
            )
        
        code = test_file.read_text()
        result = await self.execute_code(code, test_file.stem)
        result.test_file = str(test_file)
        return result
    
    async def execute_suite(self, test_files: List[Path]) -> TestSuite:
        """Execute a suite of test files"""
        self.suite.test_files = test_files
        self.suite.start_time = datetime.now()
        
        # Check dependencies
        deps = self.dependency_manager.check_dependencies()
        missing_required = [name for name, installed in deps.items() 
                          if not installed and any(d.name == name and d.required 
                          for d in self.dependency_manager.required_packages)]
        
        if missing_required:
            logger.warning(f"Missing required dependencies: {missing_required}")
            if self.config.install_dependencies:
                self.dependency_manager.install_dependencies()
        
        # Execute tests based on mode
        if self.config.execution_mode in [ExecutionMode.PARALLEL, ExecutionMode.DISTRIBUTED]:
            await self._execute_parallel(test_files)
        else:
            await self._execute_sequential(test_files)
        
        self.suite.end_time = datetime.now()
        self.suite.duration = (self.suite.end_time - self.suite.start_time).total_seconds()
        
        return self.suite
    
    async def _execute_sequential(self, test_files: List[Path]):
        """Execute tests sequentially"""
        for i, test_file in enumerate(test_files, 1):
            if self.config.verbose:
                logger.info(f"[{i}/{len(test_files)}] Executing: {test_file.name}")
            
            result = await self.execute_file(test_file)
            
            # Retry if failed
            if result.status == TestStatus.FAILED and self.config.max_retries > 0:
                for retry in range(self.config.max_retries):
                    logger.info(f"Retrying {test_file.name} (attempt {retry + 1}/{self.config.max_retries})")
                    await asyncio.sleep(self.config.retry_delay)
                    result = await self.execute_file(test_file)
                    result.retries = retry + 1
                    if result.status == TestStatus.PASSED:
                        break
            
            self.suite.add_result(result)
            
            # Fail fast if configured
            if self.config.fail_fast and result.status in [TestStatus.FAILED, TestStatus.ERROR]:
                logger.warning("Failing fast due to test failure")
                break
    
    async def _execute_parallel(self, test_files: List[Path]):
        """Execute tests in parallel"""
        logger.info(f"Executing tests in parallel with {self.config.parallel_workers} workers")
        
        semaphore = asyncio.Semaphore(self.config.parallel_workers)
        
        async def run_with_semaphore(test_file: Path) -> TestResult:
            async with semaphore:
                return await self.execute_file(test_file)
        
        tasks = [run_with_semaphore(test_file) for test_file in test_files]
        results = await asyncio.gather(*tasks, return_exceptions=True)
        
        for result in results:
            if isinstance(result, Exception):
                error_result = TestResult(
                    test_name="unknown",
                    test_file="unknown",
                    status=TestStatus.ERROR,
                    duration=0.0,
                    start_time=datetime.now(),
                    end_time=datetime.now(),
                    error_message=str(result)
                )
