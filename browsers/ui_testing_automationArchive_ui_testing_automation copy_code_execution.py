class SecuritySandbox:
    """Security sandbox for safe code execution"""
    
    def __init__(self, security_level: SecurityLevel = SecurityLevel.STANDARD):
        self.security_level = security_level
        self.violations = []
        
        # Define security rules based on level
        self.rules = self._get_security_rules()
    
    def _get_security_rules(self) -> Dict[str, Any]:
        """Get security rules based on level"""
        if self.security_level == SecurityLevel.NONE:
            return {}
        
        rules = {
            "blocked_imports": [],
            "blocked_functions": [],
            "blocked_patterns": [],
            "max_recursion": 1000,
            "max_iterations": 10000,
            "max_memory_mb": 512,
            "max_cpu_percent": 80,
            "max_file_size_mb": 10,
            "allowed_file_paths": [],
            "network_allowed": True
        }
        
        if self.security_level == SecurityLevel.BASIC:
            rules.update({
                "blocked_imports": ["os", "subprocess", "eval", "exec"],
                "blocked_functions": ["eval", "exec", "compile"],
                "blocked_patterns": [r"__import__", r"globals\(\)", r"locals\(\)"]
            })
        
        elif self.security_level == SecurityLevel.STANDARD:
            rules.update({
                "blocked_imports": ["os", "subprocess", "eval", "exec", "importlib", 
                                  "sys", "socket", "urllib", "requests"],
                "blocked_functions": ["eval", "exec", "compile", "open", "__import__"],
                "blocked_patterns": [r"__import__", r"globals\(\)", r"locals\(\)", 
                                   r"__builtins__", r"__code__", r"__class__"],
                "network_allowed": False,
                "max_memory_mb": 256,
                "max_cpu_percent": 50
            })
        
        elif self.security_level == SecurityLevel.STRICT:
            rules.update({
                "blocked_imports": ["*"],  # Block all imports except whitelisted
                "allowed_imports": ["unittest", "pytest", "math", "datetime", "json"],
                "blocked_functions": ["eval", "exec", "compile", "open", "__import__", 
                                    "input", "print"],
                "blocked_patterns": [r"__\w+__", r"getattr", r"setattr", r"delattr"],
                "network_allowed": False,
                "max_memory_mb": 128,
                "max_cpu_percent": 25,
                "max_recursion": 100,
                "max_iterations": 1000
            })
        
        return rules
    
    def validate_code(self, code: str) -> Tuple[bool, List[str]]:
        """Validate code against security rules"""
        violations = []
        
        if self.security_level == SecurityLevel.NONE:
            return True, []
        
        # Check for blocked imports
        for blocked in self.rules.get("blocked_imports", []):
            if blocked == "*":
                # Check against allowed list
                allowed = self.rules.get("allowed_imports", [])
                import_pattern = r"(?:from\s+(\w+)|import\s+(\w+))"
                matches = re.findall(import_pattern, code)
                for match in matches:
                    module = match[0] or match[1]
                    if module not in allowed:
                        violations.append(f"Import not allowed: {module}")
            elif f"import {blocked}" in code or f"from {blocked}" in code:
                violations.append(f"Blocked import detected: {blocked}")
        
        # Check for blocked functions
        for blocked in self.rules.get("blocked_functions", []):
            if blocked in code:
                violations.append(f"Blocked function detected: {blocked}")
        
        # Check for blocked patterns
        for pattern in self.rules.get("blocked_patterns", []):
            if re.search(pattern, code):
                violations.append(f"Blocked pattern detected: {pattern}")
        
        # Check for infinite loops (basic detection)
        if "while True:" in code and "break" not in code:
            violations.append("Potential infinite loop detected")
        
        # Validate AST
        try:
            ast.parse(code)
        except SyntaxError as e:
            violations.append(f"Syntax error: {e}")
        
        return len(violations) == 0, violations
    
    def create_restricted_globals(self) -> Dict[str, Any]:
        """Create restricted global namespace for execution"""
        if self.security_level == SecurityLevel.NONE:
            return {"__builtins__": __builtins__}
        
        # Create restricted builtins
        safe_builtins = {
            'None': None,
            'True': True,
            'False': False,
            'int': int,
            'float': float,
            'str': str,
            'list': list,
            'dict': dict,
            'tuple': tuple,
            'set': set,
            'len': len,
            'range': range,
            'enumerate': enumerate,
            'zip': zip,
            'map': map,
            'filter': filter,
            'sum': sum,
            'min': min,
            'max': max,
            'abs': abs,
            'round': round,
            'sorted': sorted,
            'reversed': reversed,
            'isinstance': isinstance,
            'type': type,
            'print': print,  # Can be mocked or restricted
            'Exception': Exception,
            'ValueError': ValueError,
            'TypeError': TypeError,
            'KeyError': KeyError,
            'IndexError': IndexError,
            'AssertionError': AssertionError
        }
        
        if self.security_level == SecurityLevel.STRICT:
            # Remove even more builtins in strict mode
            safe_builtins.pop('print', None)
            safe_builtins.pop('type', None)
        
        return {"__builtins__": safe_builtins}
    
    @contextlib.contextmanager
    def sandbox_context(self):
        """Context manager for sandboxed execution"""
        # Store original values
        original_recursion_limit = sys.getrecursionlimit()
        
        try:
            # Set recursion limit
            if "max_recursion" in self.rules:
                sys.setrecursionlimit(self.rules["max_recursion"])
            
            yield
            
        finally:
            # Restore original values
            sys.setrecursionlimit(original_recursion_limit)

