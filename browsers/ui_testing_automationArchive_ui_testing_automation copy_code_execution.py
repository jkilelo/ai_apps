class CodeExecutionEngine:
    """Main interface for code execution"""
    
    def __init__(self, config: Optional[ExecutionConfig] = None):
        self.config = config or ExecutionConfig()
        self.executor = TestExecutor(self.config)
        self.report_generator = ReportGenerator(self.config)
    
    async def execute(self, 
                      code: Optional[str] = None,
                      test_files: Optional[List[Path]] = None,
                      test_dir: Optional[Path] = None) -> CodeExecutionResult:
        """Execute code or test files and generate reports"""
        
        try:
            # Determine what to execute
            if code:
                # Execute single code string
                result = await self.executor.execute_code(code, "inline_test")
                suite = TestSuite(name="Inline Test", test_files=[])
                suite.add_result(result)
            elif test_files:
                # Execute specific test files
                suite = await self.executor.execute_suite(test_files)
            elif test_dir:
                # Execute all tests in directory
                test_files = list(test_dir.glob("test_*.py"))
                suite = await self.executor.execute_suite(test_files)
            else:
                return CodeExecutionResult(
                    success=False,
                    suite=TestSuite(name="Empty", test_files=[]),
                    errors=["No code or test files provided"]
                )
            
            # Generate reports
            reports = self.report_generator.generate_reports(suite)
            
            # Create result
            return CodeExecutionResult(
                success=suite.failed == 0 and suite.errors == 0,
                suite=suite,
                reports=reports,
                execution_time=suite.duration,
                metadata={
                    "config": self.config.__dict__,
                    "environment": dict(os.environ)
                }
            )
            
        except Exception as e:
            logger.error(f"Execution failed: {e}")
            return CodeExecutionResult(
                success=False,
                suite=TestSuite(name="Error", test_files=[]),
                errors=[str(e)],
                execution_time=0.0
            )
    
    async def execute_from_llm_generated(self, generated_code: str, 
                                        test_name: str = "llm_generated_test") -> CodeExecutionResult:
        """Execute code generated by code_generation_with_llm.py"""
        
        # Create temp file for the generated code
        test_file = self.config.temp_dir / f"{test_name}.py"
        test_file.write_text(generated_code)
        
        # Execute the test
        result = await self.execute(test_files=[test_file])
        
        # Clean up temp file if not in debug mode
        if not self.config.verbose:
            test_file.unlink()
        
        return result

