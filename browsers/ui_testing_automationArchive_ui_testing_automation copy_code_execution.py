class DependencyManager:
    """Manages test dependencies and installations"""
    
    def __init__(self, config: ExecutionConfig):
        self.config = config
        self.dependencies_cache = {}
        self.last_check_time = None
        self.required_packages = [
            DependencyInfo("pytest", required=True, install_command="pip install pytest"),
            DependencyInfo("pytest-asyncio", required=False, install_command="pip install pytest-asyncio"),
            DependencyInfo("pytest-xdist", required=False, install_command="pip install pytest-xdist"),
            DependencyInfo("pytest-html", required=False, install_command="pip install pytest-html"),
            DependencyInfo("pytest-timeout", required=False, install_command="pip install pytest-timeout"),
            DependencyInfo("allure-pytest", required=False, install_command="pip install allure-pytest"),
            DependencyInfo("playwright", required=False, install_command="pip install playwright"),
            DependencyInfo("selenium", required=False, install_command="pip install selenium"),
        ]
    
    def check_dependencies(self) -> Dict[str, bool]:
        """Check if required dependencies are installed"""
        # Check cache
        if self.last_check_time:
            time_since_check = (datetime.now() - self.last_check_time).seconds
            if time_since_check < self.config.dependency_check_interval:
                return self.dependencies_cache
        
        results = {}
        for dep in self.required_packages:
            try:
                __import__(dep.name.replace("-", "_"))
                dep.installed = True
                results[dep.name] = True
            except ImportError:
                dep.installed = False
                results[dep.name] = False
                if dep.required:
                    logger.warning(f"Required dependency missing: {dep.name}")
        
        self.dependencies_cache = results
        self.last_check_time = datetime.now()
        return results
    
    def install_dependencies(self, requirements_file: Optional[Path] = None) -> bool:
        """Install required dependencies"""
        if not self.config.install_dependencies:
            return True
        
        try:
            # Install from requirements file if provided
            if requirements_file and requirements_file.exists():
                logger.info(f"Installing dependencies from {requirements_file}")
                subprocess.run(
                    [sys.executable, "-m", "pip", "install", "-r", str(requirements_file)],
                    capture_output=True,
                    text=True,
                    check=True
                )
            
            # Install missing required packages
            for dep in self.required_packages:
                if not dep.installed and dep.required:
                    logger.info(f"Installing {dep.name}...")
                    subprocess.run(
                        dep.install_command.split(),
                        capture_output=True,
                        text=True,
                        check=True
                    )
            
            # Special handling for Playwright browsers
            if "playwright" in [d.name for d in self.required_packages if d.installed]:
                self._install_playwright_browsers()
            
            return True
            
        except subprocess.CalledProcessError as e:
            logger.error(f"Failed to install dependencies: {e}")
            return False
    
    def _install_playwright_browsers(self):
        """Install Playwright browsers if needed"""
        try:
            subprocess.run(
                [sys.executable, "-m", "playwright", "install", "chromium"],
                capture_output=True,
                text=True,
                check=True
            )
            logger.info("Playwright browsers installed successfully")
        except Exception as e:
            logger.warning(f"Could not install Playwright browsers: {e}")
    
    def create_virtual_environment(self, venv_path: Path) -> bool:
        """Create a virtual environment for isolated execution"""
        try:
            import venv
            venv.create(venv_path, with_pip=True)
            logger.info(f"Created virtual environment at {venv_path}")
            return True
        except Exception as e:
            logger.error(f"Failed to create virtual environment: {e}")
            return False

