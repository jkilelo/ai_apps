class LLMTestGenerationRequest(BaseModel):
    """
    Optimized structure for requesting test generation from LLMs.
    Follows best practices for structured outputs and prompt engineering.
    """
    
    # Context setting
    context: Dict[str, Any] = Field(
        ...,
        description="Context for test generation",
        example={
            "application_type": "e-commerce",
            "testing_framework": "playwright",
            "test_style": "BDD",
            "coverage_goals": ["functional", "edge_cases", "accessibility"]
        }
    )
    
    # Page structure
    page: PageStructure = Field(
        ...,
        description="Complete page structure with elements"
    )
    
    # Specific requirements
    requirements: Dict[str, Any] = Field(
        default_factory=dict,
        description="Specific test requirements",
        example={
            "focus_areas": ["payment_flow", "form_validation"],
            "exclude": ["performance_testing"],
            "max_scenarios": 10,
            "priority": "critical_paths_only"
        }
    )
    
    # Output format specification
    output_format: Dict[str, Any] = Field(
        default_factory=lambda: {
            "format": "gherkin",
            "include_examples": True,
            "include_test_data": True,
            "group_by": "user_journey"
        },
        description="Desired output format"
    )
    
    def to_llm_prompt(self) -> str:
        """Convert to optimized LLM prompt"""
        return f"""
You are an expert QA engineer. Generate comprehensive test cases for the following web page.

CONTEXT:
{json.dumps(self.context, indent=2)}

PAGE STRUCTURE:
{json.dumps(self.page.model_dump(), indent=2)}

REQUIREMENTS:
{json.dumps(self.requirements, indent=2)}

OUTPUT FORMAT:
{json.dumps(self.output_format, indent=2)}

Generate test cases that:
1. Cover all critical user journeys
2. Include positive, negative, and edge cases
3. Consider accessibility requirements
4. Follow the specified output format exactly
5. Use the provided selectors for test implementation

Return ONLY valid JSON matching the specified format.
"""


