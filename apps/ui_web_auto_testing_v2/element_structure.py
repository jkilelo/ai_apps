class LLMOptimizedElement(BaseModel):
    """
    Comprehensive element structure optimized for LLM test generation.
    
    This structure provides multiple layers of context to help LLMs:
    1. Understand the element's purpose and business context
    2. Generate meaningful test scenarios
    3. Create comprehensive test coverage
    4. Handle edge cases and error scenarios
    5. Consider accessibility and non-functional requirements
    """
    
    model_config = ConfigDict(extra="allow")
    
    # ========== CORE IDENTIFICATION ==========
    element_id: str = Field(..., description="Unique identifier for this element")
    tag_name: str = Field(..., description="HTML tag name")
    element_category: ElementCategory = Field(..., description="High-level category")
    
    # ========== SELECTORS FOR TEST EXECUTION ==========
    selectors: Dict[str, str] = Field(
        ...,
        description="Multiple selector strategies",
        example={
            "id": "submit-button",
            "css": ".btn.btn-primary",
            "xpath": "//button[@type='submit']",
            "data_testid": "submit-form-button"
        }
    )
    
    # ========== SEMANTIC CONTEXT ==========
    semantic: SemanticContext = Field(
        ...,
        description="Rich semantic context for LLM understanding"
    )
    
    # ========== INTERACTION CONTEXT ==========
    interaction: InteractionContext = Field(
        ...,
        description="How users interact with this element"
    )
    
    # ========== CONTENT ==========
    content: Dict[str, Any] = Field(
        default_factory=dict,
        description="Element content",
        example={
            "text": "Submit Order",
            "placeholder": "Enter email",
            "label": "Email Address",
            "value": "current value",
            "options": ["Option 1", "Option 2"]
        }
    )
    
    # ========== VALIDATION CONTEXT ==========
    validation: Optional[ValidationContext] = Field(
        None,
        description="Validation rules and constraints"
    )
    
    # ========== ACCESSIBILITY CONTEXT ==========
    accessibility: Optional[AccessibilityContext] = Field(
        None,
        description="Accessibility information"
    )
    
    # ========== HIERARCHICAL CONTEXT ==========
    hierarchy: Optional[HierarchicalContext] = Field(
        None,
        description="Position in page hierarchy"
    )
    
    # ========== VISUAL CONTEXT ==========
    visual: Optional[VisualContext] = Field(
        None,
        description="Visual properties"
    )
    
    # ========== STATE CONTEXT ==========
    state: Optional[StateContext] = Field(
        None,
        description="Element state information"
    )
    
    # ========== TEST METADATA ==========
    test_priority: TestPriority = Field(
        TestPriority.MEDIUM,
        description="Priority for test generation"
    )
    
    suggested_test_types: List[str] = Field(
        default_factory=list,
        description="Suggested types of tests for this element",
        example=["functional", "validation", "accessibility", "performance", "security"]
    )
    
    test_data_examples: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Example test data for this element"
    )
    
    # ========== METADATA ==========
    confidence_score: float = Field(
        1.0,
        ge=0.0,
        le=1.0,
        description="Confidence in element extraction"
    )
    
    extraction_timestamp: datetime = Field(
        default_factory=datetime.now,
        description="When element was extracted"
    )
    
    page_context: Dict[str, Any] = Field(
        default_factory=dict,
        description="Page-level context",
        example={
            "url": "https://example.com/checkout",
            "page_title": "Checkout",
            "page_type": "e-commerce_checkout"
        }
    )


