def enrich_element_for_llm(basic_element: Dict[str, Any]) -> LLMOptimizedElement:
    """
    Enrich a basic extracted element with LLM-optimized context.
    This function adds semantic understanding and test-relevant metadata.
    """
    
    # Determine element category based on tag and attributes
    category = determine_element_category(basic_element)
    
    # Build semantic context
    semantic = build_semantic_context(basic_element, category)
    
    # Build interaction context
    interaction = build_interaction_context(basic_element, category)
    
    # Create enriched element
    enriched = LLMOptimizedElement(
        element_id=basic_element.get('element_id', generate_element_id(basic_element)),
        tag_name=basic_element.get('tag_name', 'unknown'),
        element_category=category,
        selectors=extract_selectors(basic_element),
        semantic=semantic,
        interaction=interaction,
        content=extract_content(basic_element),
        validation=build_validation_context(basic_element) if needs_validation(basic_element) else None,
        accessibility=build_accessibility_context(basic_element),
        hierarchy=build_hierarchy_context(basic_element),
        visual=build_visual_context(basic_element),
        state=build_state_context(basic_element),
        test_priority=determine_test_priority(basic_element, category),
        suggested_test_types=suggest_test_types(basic_element, category),
        test_data_examples=generate_test_data_examples(basic_element, category)
    )
    
    return enriched


def determine_element_category(element: Dict[str, Any]) -> ElementCategory:
    """Determine the high-level category of an element"""
    tag = element.get('tag_name', '').lower()
    element_type = element.get('element_type', '').lower()
    role = element.get('role', '').lower()
    
    # Navigation elements
    if tag in ['nav', 'header', 'footer'] or role == 'navigation':
        return ElementCategory.NAVIGATION
    
    # Form inputs
    if tag in ['input', 'textarea', 'select'] or element_type in ['input', 'textarea', 'dropdown']:
        return ElementCategory.FORM_INPUT
    
    # Action elements
    if tag in ['button', 'a'] or element_type == 'button' or role == 'button':
        return ElementCategory.ACTION
    
    # Media elements
    if tag in ['img', 'video', 'audio', 'picture']:
        return ElementCategory.MEDIA
    
    # Data display
    if tag in ['table', 'ul', 'ol', 'dl']:
        return ElementCategory.DATA_DISPLAY
    
    # Default to content
    return ElementCategory.CONTENT


def build_semantic_context(element: Dict[str, Any], category: ElementCategory) -> SemanticContext:
    """Build semantic context for an element"""
    text = element.get('text_content', '')
    aria_label = element.get('aria_label', '')
    
    # Determine purpose based on text and category
    purpose = f"{category.value} element"
    if text:
        purpose = f"{category.value}: {text[:50]}"
    elif aria_label:
        purpose = f"{category.value}: {aria_label}"
    
    return SemanticContext(
        primary_purpose=purpose,
        keywords=extract_keywords(element),
        domain_tags=[]  # Would be enriched based on page context
    )


def build_interaction_context(element: Dict[str, Any], category: ElementCategory) -> InteractionContext:
    """Build interaction context for an element"""
    # Determine primary interaction based on category
    interaction_map = {
        ElementCategory.ACTION: InteractionPattern.CLICK,
        ElementCategory.FORM_INPUT: InteractionPattern.TYPE_TEXT,
        ElementCategory.NAVIGATION: InteractionPattern.CLICK,
        ElementCategory.DATA_DISPLAY: InteractionPattern.VALIDATE,
        ElementCategory.INTERACTIVE: InteractionPattern.SELECT_OPTION
    }
    
    return InteractionContext(
        primary_interaction=interaction_map.get(category, InteractionPattern.CLICK),
        alternative_interactions=[],
        prerequisites=[],
        expected_outcomes=[],
        common_flows=[],
        error_scenarios=[]
    )


def extract_selectors(element: Dict[str, Any]) -> Dict[str, str]:
    """Extract multiple selector strategies"""
    selectors = {}
    
    if element.get('id'):
        selectors['id'] = element['id']
    
    if element.get('css_selector'):
        selectors['css'] = element['css_selector']
    
    if element.get('xpath'):
        selectors['xpath'] = element['xpath']
    
    if element.get('data-testid'):
        selectors['data_testid'] = element['data-testid']
    
    return selectors


def extract_content(element: Dict[str, Any]) -> Dict[str, Any]:
    """Extract element content"""
    content = {}
    
    if element.get('text_content'):
        content['text'] = element['text_content']
    
    if element.get('placeholder'):
        content['placeholder'] = element['placeholder']
    
    if element.get('value'):
        content['value'] = element['value']
    
    if element.get('options'):
        content['options'] = element['options']
    
    return content


def build_validation_context(element: Dict[str, Any]) -> ValidationContext:
    """Build validation context for form elements"""
    rules = []
    
    if element.get('required'):
        rules.append(ValidationRule.REQUIRED)
    
    if element.get('pattern'):
        rules.append(ValidationRule.PATTERN)
    
    if element.get('minlength') or element.get('maxlength'):
        rules.append(ValidationRule.LENGTH)
    
    return ValidationContext(
        rules=rules,
        constraints={},
        valid_values=[],
        invalid_values=[],
        edge_cases=[],
        error_messages={}
    )


def build_accessibility_context(element: Dict[str, Any]) -> AccessibilityContext:
    """Build accessibility context"""
    return AccessibilityContext(
        aria_role=element.get('role'),
        aria_label=element.get('aria_label'),
        aria_description=element.get('aria_describedby'),
        keyboard_accessible=element.get('tab_index', -1) >= 0,
        tab_index=element.get('tab_index'),
        screen_reader_text=element.get('aria_label') or element.get('text_content')
    )


def build_hierarchy_context(element: Dict[str, Any]) -> HierarchicalContext:
    """Build hierarchical context"""
    return HierarchicalContext(
        parent_section=element.get('parent_section'),
        parent_form=element.get('parent_form'),
        siblings=[],
        children=[],
        navigation_order=element.get('tab_index')
    )


def build_visual_context(element: Dict[str, Any]) -> VisualContext:
    """Build visual context"""
    return VisualContext(
        x=element.get('x', 0),
        y=element.get('y', 0),
        width=element.get('width', 0),
        height=element.get('height', 0),
        is_visible=element.get('is_visible', True),
        is_above_fold=element.get('y', 0) < 768  # Approximate fold
    )


def build_state_context(element: Dict[str, Any]) -> StateContext:
    """Build state context"""
    return StateContext(
        is_enabled=element.get('is_enabled', True),
        is_readonly=element.get('readonly', False),
        is_required=element.get('required', False),
        is_selected=element.get('selected', False),
        is_checked=element.get('checked', False),
        possible_states=[],
        state_triggers={},
        updates_dynamically=False,
        update_triggers=[],
        depends_on=[],
        affects=[]
    )


def needs_validation(element: Dict[str, Any]) -> bool:
    """Check if element needs validation context"""
    return element.get('tag_name', '').lower() in ['input', 'textarea', 'select']


def determine_test_priority(element: Dict[str, Any], category: ElementCategory) -> TestPriority:
    """Determine test priority based on element characteristics"""
    # Critical elements
    if category in [ElementCategory.AUTHENTICATION, ElementCategory.PAYMENT]:
        return TestPriority.CRITICAL
    
    # High priority elements
    if category in [ElementCategory.ACTION, ElementCategory.FORM_INPUT]:
        return TestPriority.HIGH
    
    # Default to medium
    return TestPriority.MEDIUM


def suggest_test_types(element: Dict[str, Any], category: ElementCategory) -> List[str]:
    """Suggest appropriate test types for an element"""
    test_types = ["functional"]
    
    if category == ElementCategory.FORM_INPUT:
        test_types.extend(["validation", "boundary"])
    
    if element.get('aria_label') or element.get('role'):
        test_types.append("accessibility")
    
    if category in [ElementCategory.AUTHENTICATION, ElementCategory.PAYMENT]:
        test_types.append("security")
    
    return test_types


def generate_test_data_examples(element: Dict[str, Any], category: ElementCategory) -> List[Dict[str, Any]]:
    """Generate example test data for an element"""
    examples = []
    
    if category == ElementCategory.FORM_INPUT:
        input_type = element.get('input_type', 'text')
        
        if input_type == 'email':
            examples.extend([
                {"value": "test@example.com", "expected": "valid"},
                {"value": "invalid-email", "expected": "invalid"},
                {"value": "", "expected": "required_error"}
            ])
        elif input_type == 'number':
            examples.extend([
                {"value": "123", "expected": "valid"},
                {"value": "abc", "expected": "invalid"},
                {"value": "-1", "expected": "range_error"}
            ])
    
    return examples


def extract_keywords(element: Dict[str, Any]) -> List[str]:
    """Extract keywords from element for semantic understanding"""
    keywords = []
    
    # Extract from text content
    if element.get('text_content'):
        words = element['text_content'].lower().split()
        keywords.extend([w for w in words if len(w) > 3][:5])
    
    # Extract from aria-label
    if element.get('aria_label'):
        words = element['aria_label'].lower().split()
        keywords.extend([w for w in words if len(w) > 3][:3])
    
    return list(set(keywords))


def generate_element_id(element: Dict[str, Any]) -> str:
    """Generate unique element ID"""
    import hashlib
    
    # Create ID from element properties
    id_source = f"{element.get('tag_name', '')}_{element.get('xpath', '')}_{element.get('text_content', '')}"
    return hashlib.md5(id_source.encode()).hexdigest()[:8]


