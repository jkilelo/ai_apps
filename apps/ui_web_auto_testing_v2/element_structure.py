#!/usr/bin/env python3
"""
LLM-Optimized Element Extraction Structure for UI Test Generation

This module defines the optimal JSON structure for element extraction that maximizes
the quality of test cases generated by LLMs. Based on research and best practices
for LLM interaction, structured outputs, and UI testing requirements.

The structure is designed to:
1. Provide rich semantic context for LLMs to understand the UI
2. Include hierarchical relationships for understanding page structure
3. Capture interaction patterns and user journeys
4. Enable generation of comprehensive test scenarios
5. Support both functional and non-functional test generation
"""

from typing import List, Dict, Any, Optional, Union, Literal
from datetime import datetime
from enum import Enum
from pydantic import BaseModel, Field, ConfigDict, field_validator
import json


# ============================================================================
# ENHANCED ENUMS FOR BETTER LLM UNDERSTANDING
# ============================================================================

class ElementCategory(str, Enum):
    """High-level element categories that LLMs can reason about"""
    NAVIGATION = "navigation"          # Navigation elements
    FORM_INPUT = "form_input"         # Form inputs and fields
    ACTION = "action"                 # Buttons, links that trigger actions
    CONTENT = "content"               # Static content display
    MEDIA = "media"                   # Images, videos, audio
    FEEDBACK = "feedback"             # Alerts, notifications, messages
    DATA_DISPLAY = "data_display"     # Tables, lists, grids
    INTERACTIVE = "interactive"       # Dropdowns, sliders, toggles
    AUTHENTICATION = "authentication" # Login, signup, password elements
    PAYMENT = "payment"               # Payment-related elements
    SEARCH = "search"                 # Search bars and filters
    SOCIAL = "social"                 # Social media elements

class InteractionPattern(str, Enum):
    """Common interaction patterns for test generation"""
    CLICK = "click"
    TYPE_TEXT = "type_text"
    SELECT_OPTION = "select_option"
    DRAG_DROP = "drag_drop"
    HOVER = "hover"
    SCROLL = "scroll"
    UPLOAD_FILE = "upload_file"
    KEYBOARD_SHORTCUT = "keyboard_shortcut"
    MULTI_STEP = "multi_step"
    VALIDATE = "validate"
    WAIT = "wait"

class TestPriority(str, Enum):
    """Test priority based on element importance"""
    CRITICAL = "critical"     # Core functionality
    HIGH = "high"            # Important features
    MEDIUM = "medium"        # Standard features
    LOW = "low"              # Nice-to-have features
    EXPLORATORY = "exploratory"  # Edge cases

class ValidationRule(str, Enum):
    """Validation rules that can be tested"""
    REQUIRED = "required"
    FORMAT = "format"
    LENGTH = "length"
    RANGE = "range"
    PATTERN = "pattern"
    UNIQUENESS = "uniqueness"
    DEPENDENCY = "dependency"
    BUSINESS_LOGIC = "business_logic"


